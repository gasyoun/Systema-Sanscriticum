<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Анти-бот защита формы подписки (H324)
    |--------------------------------------------------------------------------
    |
    | Форма /subscribe при каждой отправке создаёт кабинетного пользователя и
    | шлёт письмо с magic-ссылкой на указанный email. Без защиты боты используют
    | её как рассыльщик спама по чужим ящикам (subscription-bombing), что бьёт по
    | доставляемости домена и засоряет метрики. Защита — чисто серверная, без
    | внешних сервисов: honeypot + time-trap + блок одноразовых доменов.
    |
    | Пороги env-backed — не хардкодим (как в config/receivables.php и др.).
    |
    */
    'antibot' => [

        // Минимум секунд между рендером формы и сабмитом. Человек физически не
        // заполнит форму мгновенно; боты (и прямые POST без метки) — да.
        'min_fill_seconds' => (int) env('NEWSLETTER_MIN_FILL_SECONDS', 3),

        // Максимальный возраст метки времени формы (сек). Защита от переигранной
        // старой метки; щедрый дефолт (12 ч), чтобы не резать реальных людей с
        // долго открытой вкладкой. За пределами — считаем ботом.
        'max_form_age_seconds' => (int) env('NEWSLETTER_MAX_FORM_AGE_SECONDS', 12 * 60 * 60),

        // Одноразовые/спам-домены — вспомогательный сигнал (основную работу
        // делают honeypot + time-trap). Список через запятую в env; дефолт — то,
        // что уже наблюдалось в атаке.
        'blocked_email_domains' => array_values(array_filter(array_map(
            'trim',
            explode(',', (string) env(
                'NEWSLETTER_BLOCKED_DOMAINS',
                'immenseignite.info,swagpapa.com'
            ))
        ))),
    ],
];
