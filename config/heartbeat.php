declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Пульс планировщика — внешний сторож для «сервер молчит» (H1713)
    |--------------------------------------------------------------------------
    |
    | Мотив. 24–26.07.2026 samskrte.ru лежал двое суток, и об этом никто не
    | знал (issue #730). Внешний монитор доступности, заведённый после того
    | разбора, закрывает вопрос «отвечает ли сайт», но у него есть две дыры,
    | которые закрывает именно пульс:
    |
    |   1) «Сайт жив, а планировщик или Horizon умерли». Тогда сайт отдаёт
    |      страницы как ни в чём не бывало, а рассылки, напоминания, списания
    |      и выкладка молча стоят. Снаружи это неотличимо от нормы.
    |
    |   2) Частота. Монитор на GitHub Actions просит крон «раз в 10 минут», но
    |      за сутки 27-07-2026 доехало 10 плановых прогонов из 123 (8.1 %),
    |      медианный разрыв 122 мин, максимальный 230 мин. То есть реальное
    |      время обнаружения простоя — часы, а не десять минут. Пульс идёт
    |      с нашего сервера и по нашему расписанию, поэтому его частота
    |      настоящая, а не «как повезёт у GitHub».
    |
    | Как работает. Раз в `cron` планировщик дёргает уникальный URL на
    | https://healthchecks.io. Пришёл пинг — тихо; не пришёл в срок — сервис
    | сам поднимает тревогу. Инверсия обычного мониторинга: сторож снаружи и
    | срабатывает на МОЛЧАНИЕ, поэтому переживает смерть всего сервера — в
    | отличие от любой проверки, запущенной на самой машине.
    |
    | Пусто → выключено. Ключ отсутствует в .env — команда ничего не шлёт и
    | завершается успешно. Это сознательный fail-open: сторож, роняющий
    | планировщик, вреднее той болезни, которую он лечит.
    |
    */

    // Уникальный URL проверки с healthchecks.io, вида https://hc-ping.com/<uuid>.
    // Пусто = пульс выключен. Секретом не является, но и публиковать незачем:
    // знающий URL может подделать «всё хорошо», поэтому держим в .env.
    'url' => (string) env('HEARTBEAT_PING_URL', ''),

    // Частота пульса. По умолчанию раз в 5 минут: столько же стоит один
    // HTTP-запрос, а окно необнаруженного простоя сокращается с часов
    // (см. измерение GitHub-крона выше) до минут. В healthchecks.io период
    // проверки задаётся отдельно — выставить там тот же шаг плюс запас
    // (period 5 мин, grace 10 мин), иначе сторож будет ложно тревожить.
    'cron' => (string) env('HEARTBEAT_CRON', '*/5 * * * *'),

    // Таймаут запроса. Короткий сознательно: пульс не должен задерживать
    // очередь планировщика, а пропущенный пинг и так поднимет тревогу.
    'timeout' => (int) env('HEARTBEAT_TIMEOUT', 10),

    // Проверять ли заодно, что жив Horizon. Именно он тянет очереди, то есть
    // все отложенные задачи; его смерть — вторая половина сценария «сайт жив,
    // а работа стоит». При провале шлём /fail, и тревога поднимается сразу,
    // не дожидаясь истечения периода.
    'check_horizon' => (bool) env('HEARTBEAT_CHECK_HORIZON', true),

];
