<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Слежка за ростом файлового хранилища (H1345)
    |--------------------------------------------------------------------------
    |
    | На 19-07-2026 всё storage/app занимает ~20 МБ, то есть проблема не в
    | ёмкости, а в ОТСУТСТВИИ СИГНАЛА: до этой команды ни одна метрика роста
    | не измерялась вообще (`disk_free_space`/`du` не встречались в коде ни
    | разу). Загрузки при этом ничем не ограничены по количеству, поэтому
    | заметить проблему можно было только тогда, когда сервер уже лёг.
    |
    | Два независимых сигнала, оба нужны:
    |   1) объём самих каталогов загрузок — растёт предсказуемо, ловится рано;
    |   2) свободное место на диске — ловит и то, что растёт мимо storage/app
    |      (логи, MySQL, бэкапы), то есть настоящую причину «сервер лёг».
    |
    | Пороги здесь env-backed по домовому правилу (никаких чисел в сервисе или
    | странице). Светофор тот же, что у дебиторки: зелёный < warn_ratio,
    | жёлтый warn_ratio…1.0, красный >= 1.0.
    |
    */

    // Каталоги под наблюдением: путь относительно storage/app => потолок в МБ.
    // Потолки выбраны как «в ~50-100 раз выше сегодняшнего факта» — они ловят
    // аномальный рост, а не нормальную работу. Уточнить после первого месяца
    // реальных измерений (@DECIDE MG).
    'watched' => [
        'public/lesson-materials' => (int) env('STORAGE_WATCH_LESSON_MATERIALS_MB', 5000),
        'homework' => (int) env('STORAGE_WATCH_HOMEWORK_MB', 2000),
        'public/subscriber-magnets' => (int) env('STORAGE_WATCH_MAGNETS_MB', 500),
        'archives' => (int) env('STORAGE_WATCH_ARCHIVES_MB', 500),
        'lectures' => (int) env('STORAGE_WATCH_LECTURES_MB', 500),
    ],

    // Суммарный потолок на всё storage/app, МБ. Отдельно от суммы каталогов
    // выше: ловит рост в каталогах, которых ещё нет в списке.
    'total_mb' => (int) env('STORAGE_WATCH_TOTAL_MB', 8000),

    // Доля от потолка, с которой начинается жёлтая зона (предупреждение
    // приходит ДО того, как что-то сломается).
    'warn_ratio' => (float) env('STORAGE_WATCH_WARN_RATIO', 0.8),

    // Свободное место на диске, ниже которого это уже инцидент, а не рост.
    // Проверка отключается значением 0 — в контейнере (Sail/Docker) PHP видит
    // файловую систему контейнера, а не хостовый том, и число вводит в
    // заблуждение.
    'min_free_disk_mb' => (int) env('STORAGE_WATCH_MIN_FREE_DISK_MB', 2048),

    // Сколько файлов сканировать за один проход, предохранитель: рекурсивный
    // обход дорожает линейно с ростом медиа, а команда ходит ежедневно.
    // При превышении каталог отдаёт частичный итог и помечается как усечённый —
    // молча недосчитать хуже, чем громко сказать «не смог посчитать».
    'scan_file_cap' => (int) env('STORAGE_WATCH_SCAN_FILE_CAP', 20000),

];
