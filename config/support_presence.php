<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Проактивный монитор посетителей веб-чата (H1197, Jivo-паритет Pillar 2)
|--------------------------------------------------------------------------
|
| Тонкие настройки presence-слоя, отделённые от deploy-рубильника
| features.support_visitor_presence, чтобы менять окна без правки кода.
| Считываются на каждый запрос — правка через .env подхватывается сразу
| (config:clear на проде). Модель — heartbeat-beacon: виджет периодически
| стучит POST /support/presence, сервер апсертит строку support_visitor_presences.
*/

return [
    /*
     | Как часто виджет шлёт beacon (сек). Клиент читает это значение из
     | data-атрибута, отрендеренного в partials/support-chat-widget.blade.php.
     | Меньше — «живее» список у куратора и быстрее долетает проактив, но больше
     | запросов. Дефолт 20с — куратор видит посетителя почти в реальном времени
     | при щадящей нагрузке.
     */
    'beacon_interval_seconds' => (int) env('SUPPORT_PRESENCE_BEACON_SECONDS', 20),

    /*
     | Окно «онлайн»: посетитель считается присутствующим на сайте, если его
     | последний beacon был не позднее N секунд назад. Должно быть заметно
     | больше beacon_interval_seconds (пропущенный пакет не должен «гасить»
     | посетителя). Дефолт 75с ≈ 3 пропущенных beacon'а при интервале 20с.
     */
    'online_window_seconds' => (int) env('SUPPORT_PRESENCE_ONLINE_SECONDS', 75),

    /*
     | Через сколько минут простоя строка присутствия удаляется вымётывающей
     | джобой (PruneStaleVisitorPresencesJob, каждые 5 минут по расписанию).
     | Таблица эфемерная — храним ровно столько, сколько нужно куратору,
     | персональные данные анонимного посетителя не залёживаются. Дефолт 15 мин.
     */
    'prune_after_minutes' => (int) env('SUPPORT_PRESENCE_PRUNE_MINUTES', 15),
];
