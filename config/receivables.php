<?php

declare(strict_types=1);

return [
    /*
    |--------------------------------------------------------------------------
    | Управление рассрочкой и дебиторкой — пороги и лимиты (H257, фаза C).
    |--------------------------------------------------------------------------
    | Держим цифры здесь (а не хардкодом в вёрстке/сервисе), чтобы владелец
    | вывел себя из ручного мониторинга: делегированный финдир/бухгалтер видит
    | «красное/жёлтое/зелёное» и меняет пороги через .env без деплоя.
    |
    | Смысл — из антикейса онлайн-школы «Алохомора»: ввели рассрочку без
    | согласования с финдиром → ученики платили 50 %, бросали, остаток не
    | доплачивали; за 3 недели накопилась неликвидная дебиторка ≈ месячной
    | выручке (~2 млн ₽) → кассовый разрыв «прибыль есть, а денег нет».
    |
    | Дебиторка здесь = сумма НЕПОГАШЕННЫХ обещаний оплаты (payment_promises со
    | статусом active/expired и заданной суммой). Обещания, объединённые
    | installment_group_id, — это дебиторка ОТ РАССРОЧКИ; одиночные — прочая.
    */

    // Порог «максимально допустимой дебиторки». Два режима:
    //  'revenue_share' — порог = share × выручка за trailing-окно (антикейс:
    //                    дебиторка ≈ месячной выручке = разрыв, поэтому держим
    //                    планку НИЖЕ месячной выручки);
    //  'fixed'         — фиксированная сумма ₽ (когда финмодель дала абсолют).
    'threshold' => [
        'mode' => env('RECEIVABLES_THRESHOLD_MODE', 'revenue_share'), // revenue_share|fixed

        // Доля выручки за окно, которую дебиторка не должна превышать. 0.5 =
        // «не больше половины месячной выручки» — консервативный дефолт против
        // антикейса (там дебиторка доросла до 100 % месячной выручки). @DECIDE MG.
        'revenue_share' => (float) env('RECEIVABLES_THRESHOLD_REVENUE_SHARE', 0.5),

        // Окно, за которое меряем «месячную» выручку (реальные оплаченные
        // школьные платежи, кроме техрасходов/выплат ЗП/предоплат).
        'revenue_window_days' => (int) env('RECEIVABLES_REVENUE_WINDOW_DAYS', 30),

        // Абсолютный порог для режима 'fixed', ₽.
        'fixed_amount' => (float) env('RECEIVABLES_THRESHOLD_FIXED', 500000),
    ],

    // Через сколько дней ПОСЛЕ обещанной даты долг считается неликвидным
    // (высокий риск невозврата). Антикейс: 3 недели просрочки = катастрофа,
    // поэтому дефолт 14 дней — ранний сигнал, а не пост-фактум. @DECIDE MG.
    'illiquid_after_days' => (int) env('RECEIVABLES_ILLIQUID_DAYS', 14),

    // Жёсткие лимиты рассрочки (предписание кейса: по %, по количеству, по сроку).
    'installment_limits' => [
        // Макс. доля продаж в рассрочку (по числу планов среди привлечений за
        // trailing-окно), %. Выше — слишком много продаётся «в долг».
        'max_share_pct' => (float) env('RECEIVABLES_MAX_INSTALLMENT_SHARE', 30),

        // Макс. число одновременно активных планов рассрочки.
        'max_concurrent' => (int) env('RECEIVABLES_MAX_CONCURRENT', 50),

        // Макс. срок одного плана рассрочки, месяцев (от первого до последнего
        // платежа). Длиннее — риск, что ученик отвалится до конца графика.
        'max_term_months' => (int) env('RECEIVABLES_MAX_TERM_MONTHS', 3),
    ],

    // Светофор по заполнению порога (доля дебиторки от порога):
    //  < warn_ratio            — зелёный (в норме),
    //  warn_ratio … < 1.0      — жёлтый (близко к порогу),
    //  ≥ 1.0 или пробит лимит  — красный (превышение — это и есть алерт).
    'warn_ratio' => (float) env('RECEIVABLES_WARN_RATIO', 0.8),
];
