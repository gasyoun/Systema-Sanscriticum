<h3>Открыть/отозвать доступ позже</h3>
<p>В карточке студента → вкладка «Обещания оплатить»:</p>
<ul>
    <li><span class="badge badge-info">Открыть доступ</span> — видно, пока доступ не открыт. <em>Скрыто для 🚩.</em></li>
    <li><span class="badge badge-danger">Отозвать доступ</span> — видно, когда открыт. Удаляет conditional-платежи <strong>и одновременно дублирует уведомление студенту во все каналы</strong>: Telegram, email, VK, Max. Это страховка на случай блокировок (например, недоступен Telegram).</li>
</ul>
<p>В action отзыва можно вписать комментарий для студента — он попадет во все 4 канала. После выполнения Filament покажет менеджеру отчет по каналам: <code>telegram: sent</code>, <code>email: sent</code>, <code>vk: skipped:no_vk_id</code>, <code>max: failed:auth</code>. Отчет также сохраняется на самом обещании в полях <code>revocation_notified_at</code> и <code>revocation_channels_sent</code> (JSON) — чтобы потом можно было посмотреть, дошло ли уведомление, без перепрогона.</p>

<h3>Что происходит под капотом</h3>
<ul>
    <li>Создается «conditional» Payment со статусом <code>paid</code> и флагом <code>is_conditional=true</code>, привязанный к обещанию через <code>linked_promise_id</code>.</li>
    <li>«Весь курс» — один Payment с тарифом <code>full</code>. «Конкретные блоки» — по одному Payment на каждый блок с тарифом <code>block_X</code>.</li>
    <li>Студент попадает в группы курса, уроки открыты согласно тарифам.</li>
    <li>Conditional Payments <strong>не считаются оплатой</strong>: должник остается в списке, прана не начисляется, welcome-email не уходит, в Google Sheets такие платежи не синкаются.</li>
    <li>В TG студенту уходит спец-уведомление «доступ открыт по договоренности до DD.MM», а не стандартное «оплата получена».</li>
</ul>

