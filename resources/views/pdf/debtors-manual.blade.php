<h2>5. Группировка и фильтры</h2>
<p>Над таблицей справа — кнопка фильтров. Доступно:</p>
<ul>
    <li><strong>Курс</strong> — мультивыбор. Полезно, когда нужно работать по одному курсу за раз.</li>
    <li><strong>Тип долга</strong> — отдельно «не продлившие» и «без оплат». Разные сегменты — разные стратегии общения.</li>
    <li><strong>Каналы связи</strong>: «Есть Telegram», «Есть VK», «Есть Max», «Есть телефон», «Есть email», «Есть Instagram», «Есть Facebook» — отсекают тех, до кого по этому каналу не достучаться.</li>
    <li><strong>Статус обучения</strong> — мультивыбор. Активные статусы (Записался / Рассрочка / Приостановка / Вернулся). Полезно, например, сфокусироваться только на «Рассрочке» при сверке графиков.</li>
    <li><strong>Неблагонадёжные</strong>: «Все» / «Только 🚩» / «Скрыть 🚩». Чтобы либо сфокусироваться только на рецидивистах, либо наоборот их не показывать.</li>
    <li><strong>Обещание оплатить</strong>: «Все» / «С обещанием» / «Без обещания». Сначала имеет смысл закрыть тех, у кого обещаний ещё нет.</li>
</ul>
<p>По умолчанию строки отсортированы по имени студента. Пагинация — 25 на странице (есть выбор 50 / 100).</p>

<h2>6. Меню действий по строке</h2>
<p>В правом столбце каждой строки — иконка-меню (три точки). Внутри:</p>
<ol>
    <li><span class="badge badge-success">Подтвердить оплату</span> — видна, когда есть активное обещание. Создаёт реальный Payment и закрывает обещание.</li>
    <li><span class="badge badge-warn">Напомнить в TG/VK</span> — видна, когда у студента привязан хотя бы один мессенджер. Индивидуальное сообщение.</li>
    <li><strong>Договориться</strong> — создать или обновить одиночное обещание оплаты. Можно сразу открыть доступ. <em>Скрыто, если студент помечен как 🚩.</em></li>
    <li><strong>Рассрочка</strong> — создать план из нескольких обещаний с разными датами. Можно сразу открывать доступ поблочно. <em>Скрыто, если студент помечен как 🚩.</em></li>
    <li><strong>🚩 Отметить как неблагонадёжного</strong> — поднять флаг с обязательным комментарием-причиной. Подробнее — раздел 12.</li>
    <li><strong>Снять флаг неблагонадёжности</strong> — видна только когда флаг уже стоит. Восстанавливает loyalty и доступ к обещаниям.</li>
    <li><strong>Карточка студента</strong> — открывает полную карточку пользователя в новой вкладке.</li>
</ol>

<h2>7. Подтвердить оплату</h2>
<p>Когда деньги пришли — заходим в меню действий → «Подтвердить оплату». Модалка:</p>
<ul>
    <li><strong>Сумма</strong> — по умолчанию подставляется либо сумма из обещания, либо рассчитанная сумма долга.</li>
    <li><strong>Блок с № / по №</strong> — по умолчанию заполняется диапазон неоплаченных блоков.</li>
    <li><strong>Идентификатор транзакции</strong> — по умолчанию <code>promise_#&lt;id&gt;</code>. Можно изменить.</li>
    <li>Тогл <strong>«Не уведомлять студента в TG»</strong> (silent) — для фиксации факта прошлой оплаты задним числом, чтобы студенту не пришло «оплата получена» прямо сейчас.</li>
</ul>
<p>После «Подтвердить» — создаётся Payment в статусе <code>paid</code>, обещание помечается <span class="badge badge-success">Выполнено</span>, студент попадает в группу курса, начисляется прана, идёт синк в Google Sheets.</p>

<div class="warn">
    <strong>silent отличается от conditional access</strong>: silent фиксирует ОПЛАТУ задним числом (фин-отчёты считают её настоящей), а conditional access (раздел 9) даёт ДОСТУП без оплаты (фин-отчёты её не видят). Не путайте.
</div>

<h2>8. Напомнить в TG/VK (по одному студенту)</h2>
<p>В меню действий → «Напомнить в TG/VK». Это персональное напоминание одному студенту:</p>
<ul>
    <li>Поле «Текст напоминания» с предзаполненным шаблоном.</li>
    <li>Доступные плейсхолдеры: <code>{name}</code>, <code>{course}</code>, <code>{block}</code>.</li>
    <li>Тогглы «Telegram» и «VK» — выбор куда отправлять (по умолчанию включены те каналы, что у студента привязаны).</li>
</ul>
<p>Если нужно отправить одинаковое напоминание сразу нескольким — используйте массовое действие (раздел 10).</p>

<h2>9. Договорённости и рассрочка</h2>

<h3>Одиночное обещание — «Договориться»</h3>
<p>Меню действий → «Договориться». Поля:</p>
<ul>
    <li><strong>Дата обещанной оплаты</strong> — по умолчанию +7 дней.</li>
    <li><strong>Сумма</strong> — можно пусто (= «оплатит весь текущий долг»).</li>
    <li><strong>Комментарий</strong> — например «получит зарплату 25-го».</li>
    <li>Тогл <strong>«Открыть доступ под обещание»</strong> — см. раздел 9.</li>
</ul>
<p>Обещание сохраняется в статусе <span class="badge badge-warn">Активно</span>. Студенту автоматических сообщений не уходит (если не включён тогл «Открыть доступ» — тогда уходит уведомление об открытии).</p>

<h3>Рассрочка</h3>
<p>Меню действий → «Рассрочка». Модалка с таблицей «График платежей»:</p>
<ul>
    <li>Минимум 2 строки, по умолчанию 3. Первая дата = сегодня + 7, следующие — с шагом +1 месяц.</li>
    <li>Если сумма долга уже посчитана — суммы автоподставятся поровну, остаток в последний платёж.</li>
    <li>В каждой строке дополнительно поля <strong>«Откр. с блока №»</strong> и <strong>«по №»</strong>. Заполняйте их, если этот платёж сразу должен открыть студенту доступ к диапазону блоков. См. раздел 9.</li>
    <li>«Комментарий ко всему плану» — общий для всех строк рассрочки.</li>
</ul>
<p>После сохранения создаётся N обещаний, объединённых общим id плана. В RelationManager у пользователя они помечены бейджем <span class="badge badge-info">#xxxxxxxx</span> — короткий id рассрочки.</p>

<div class="note">
    <strong>Когда выбирать рассрочку, а не одно обещание?</strong> Когда студент явно говорит «по столько-то в месяц», или когда долг крупный (3+ блока). Одно обещание — для разовых ситуаций «оплачу 25-го».
</div>

<h3>Отмена</h3>
<ul>
    <li><strong>Одно обещание</strong> — в RelationManager → «Отменить» на строке. Статус становится <span class="badge badge-gray">Отменено</span>.</li>
    <li><strong>Вся рассрочка целиком</strong> — в RelationManager на любой строке плана → «Отменить всю рассрочку». Все активные обещания плана отменяются разом. Уже выполненные не трогаются.</li>
</ul>

<h2>10. Открыть доступ под обещание (conditional access)</h2>
<p>По умолчанию обещание и рассрочка <strong>сами по себе не открывают доступ</strong> — это просто заметка о договорённости. Но если студенту нужно начать учиться до фактической оплаты, можно <strong>открыть доступ в кредит</strong>. Деньги при этом не считаются полученными, должник остаётся должником, но материалы открываются.</p>

<h3>Два режима</h3>
<ul>
    <li><strong>Весь курс</strong> — открывается весь курс целиком (все блоки, включая будущие). Подходит для одиночного обещания.</li>
    <li><strong>Конкретные блоки</strong> — открываются только указанные номера. Через запятую (<code>5, 6, 7</code>) или диапазоном (<code>1-3, 5</code>). Подходит для рассрочки, где каждый взнос открывает свой сегмент.</li>
</ul>

<h3>При создании одиночного обещания</h3>
<ol>
    <li>«Договориться» → заполните дату, сумму, комментарий.</li>
    <li>Включите тогл <strong>«Открыть доступ под обещание»</strong>.</li>
    <li>Выберите режим («Весь курс» или «Конкретные блоки»), для второго — введите номера.</li>
    <li>«Сохранить». Студенту уходит TG: «Доступ к {курс/блокам} открыт по договорённости до DD.MM».</li>
</ol>

