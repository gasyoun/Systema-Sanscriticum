    <tr><td>25.05</td><td>10 000 ₽</td><td>5</td><td>7</td><td>При сохранении плана откроется доступ к блокам 5–7</td></tr>
    <tr><td>25.06</td><td>10 000 ₽</td><td>8</td><td>10</td><td>Откроется доступ к блокам 8–10 одновременно (как аванс)</td></tr>
    <tr><td>25.07</td><td>10 000 ₽</td><td>—</td><td>—</td><td>Только обещание, без открытия доступа</td></tr>
    </tbody>
</table>
<p>Если поля блоков пустые — это просто финансовое обещание без открытия доступа.</p>

<div class="note">
    <strong>На практике</strong> чаще всего открывают весь предполагаемый объём рассрочки сразу при создании. Студент начинает учиться, а помесячные обещания служат напоминанием. Если по какой-то строке оплата не приходит — отзываете доступ к её блокам вручную.
</div>

<h3>Открыть/отозвать доступ позже</h3>
<p>Если обещание уже создано без открытия доступа, или нужно отозвать ранее открытый — действия доступны на строке промиса в RelationManager:</p>
<ul>
    <li><span class="badge badge-info">Открыть доступ</span> — видна, пока доступ не открыт. <em>Скрыта для студентов с флагом 🚩.</em></li>
    <li><span class="badge badge-danger">Отозвать доступ</span> — видна, когда открыт. Удаляет conditional-платежи и <strong>одновременно дублирует уведомление студенту в Telegram, на email, в VK и в Max</strong> — все каналы, по которым у нас есть его контакт. Это страховка на случай, если в РФ заблокирован Telegram. В Filament-уведомлении менеджеру показано, по каким каналам ушло и по каким нет (например, «vk: skipped:no_vk_id»). В action можно вписать комментарий для студента — он попадёт во все 4 канала.</li>
</ul>
<p>В RM в колонке <strong>«Доступ»</strong> бейдж <span class="badge badge-success">открыт</span> показывает, есть ли активный conditional-доступ по этому обещанию.</p>
<p>На странице «Должники» те же кнопки доступны в нижней части модалки активного обещания.</p>

<h3>Что происходит под капотом</h3>
<ul>
    <li>Создаётся «conditional» Payment со статусом <code>paid</code> и флагом <code>is_conditional=true</code>. Привязан к обещанию через <code>linked_promise_id</code>.</li>
    <li>Для «полного курса» — один Payment с тарифом <code>full</code>. Для «конкретных блоков» — по одному Payment на каждый блок с тарифом <code>block_X</code>.</li>
    <li>Студент попадает в группы курса (видит курс в дашборде), уроки открыты согласно тарифам.</li>
    <li>Conditional Payments <strong>не считаются оплатой</strong>: должник остаётся должником в списке, прана не начисляется, welcome-email не уходит, в Google Sheets такие платежи не синкаются.</li>
    <li>Студенту в TG уходит специальное уведомление: «доступ открыт по договорённости до DD.MM», а не стандартное «оплата получена».</li>
</ul>

