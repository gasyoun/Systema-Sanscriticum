<h2>1. Что такое сервис «Должники»</h2>
<p>Это рабочий список студентов, у которых начался блок курса, но он не оплачен. Сервис нужен для звонков, напоминаний, оформления договоренностей по оплате и контроля рассрочек.</p>
<p>Каждая строка — пара <strong>(студент, курс)</strong>. У одного студента может быть несколько строк, если он должен по разным курсам. Тип долга бывает двух видов:</p>
<ul>
    <li><strong>Не продлил</strong> — студент когда-то платил, но не оплатил текущий блок. «Теплый» долг, обычно достаточно напоминания.</li>
    <li><strong>Без оплат</strong> — студент записан на курс, но никогда не платил. Либо лид, либо забытая запись.</li>
</ul>

<h3>Кто НЕ попадает в список</h3>
<p>Из выборки автоматически исключаются студенты, у которых в карточке «Обучается на курсах» по этому курсу стоит один из <em>терминальных</em> статусов: <span class="badge badge-danger">Покинул</span>, <span class="badge badge-danger">Исключен</span>, <span class="badge badge-success">Выпускник</span> или <span class="badge badge-warn">Льготник</span>. У первых трех обучение завершено, у льготника оно бесплатное по договоренности. Долг им начислять некорректно, и в списке должников их быть не должно.</p>
<p>Для всех терминальных статусов в форме статуса есть поле <strong>«Блок выхода»</strong> — номер блока этого курса, на/после которого студент вышел. Это полезная справка для отчетности (например, «выпустился после 8-го блока»). Долги по блокам после «блока выхода» система не начисляет.</p>

<h2>2. Дашборд: виджеты «Общий итог» и «Скоро срок»</h2>

<h3>На странице «Должники»</h3>
<p>Над таблицей — четыре карточки сводки:</p>
<ul>
    <li><strong>Должников</strong> — сколько пар (студент × курс) в текущей выборке.</li>
    <li><strong>Общий долг</strong> — сумма всех долгов. Пометка «(часть «≈»)» означает, что для каких-то пар часть блоков посчитана по средней цене (точного тарифа на блок не было).</li>
    <li><strong>Просроченных обещаний</strong> — активные promises, у которых дата уже прошла. Первоочередные кандидаты на «отозвать или продлить».</li>
    <li><strong>Неблагонадежных</strong> — сколько студентов помечены флагом 🚩.</li>
</ul>

<h3>На главном дашборде админки</h3>
<p>Виджет <strong>«Скоро срок оплаты (7 дней)»</strong> показывает обещания, у которых <code>promised_at</code> попадает в ближайшие 7 дней (включая уже просроченные). Удобно открыть в начале рабочей недели и сразу видеть, у кого подходит срок, не заходя в страницу должников.</p>

