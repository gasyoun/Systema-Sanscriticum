</div>

<h2>11. Разовый доступ к одному уроку</h2>
<p>Иногда нужно открыть студенту <strong>один конкретный урок</strong> — без покупки целого блока. Самый частый сценарий: первое занятие первого блока было бесплатным в рекламных целях, но студент пропустил его и хочет вместо этого попасть, например, на 2-е занятие 3-го блока. Это <strong>общая</strong> возможность — она не привязана ни к долгу, ни к обещанию, и доступна для любого студента, даже если у него нет ни одного непогашенного долга.</p>
<p>Где: карточка студента (<code>/admin/users/{id}/edit</code>) → вкладка <strong>«Разовые доступы к урокам»</strong>. В правом верхнем углу таблицы — кнопка <span class="badge badge-info">Выдать доступ к уроку</span>. В модалке:</p>
<ul>
    <li><strong>Курс</strong> — список всех активных курсов. После выбора курса второй селект «Урок» становится активным.</li>
    <li><strong>Урок</strong> — все уроки выбранного курса, отсортированы по блокам, с подписью «Блок №X · название». Поиск по названию работает.</li>
    <li><strong>Действует до</strong> (опционально) — дата окончания. Пусто = бессрочно.</li>
    <li><strong>Причина</strong> — короткий комментарий «зачем» для аудита (необязателен, но желателен).</li>
</ul>
<p>После «Сохранить» создаётся запись в таблице <code>lesson_access_grants</code>. Студент сразу видит этот урок открытым, остальной блок остаётся закрытым. Это никак не пересекается с conditional-доступом и не влияет на «Долг».</p>
<p><strong>Отзыв</strong>: на строке гранта в той же вкладке — кнопка <span class="badge badge-danger">Отозвать</span>. Доступ закрывается, статус строки становится «отозван», студенту уходит TG «доступ к уроку закрыт». Если у гранта стояло поле «действует до» и дата прошла — статус автоматически становится «истёк» (без явного отзыва).</p>
<p>Для студентов с флагом 🚩 кнопка «Выдать доступ к уроку» скрыта (и сам сервис кидает ошибку — двойная защита).</p>

<h2>12. Неблагонадёжные студенты (рецидивисты)</h2>
<p>Если студент <strong>регулярно</strong> срывает обещания оплаты без предупреждения, его «прана сгорает». Это рабочий термин: студент теряет привилегии — скидку лояльности, возможность взять рассрочку, возможность получить conditional-доступ под честное слово.</p>

<h3>Что меняется при флаге 🚩</h3>
<ul>
    <li><strong>Скидка лояльности отключается</strong>: <code>Tariff::getDiscountPercentForUser()</code> возвращает 0, независимо от количества купленных курсов. Цены за блоки/курсы для этого студента — без оптовой скидки.</li>
    <li><strong>Действия «Договориться» и «Рассрочка» скрыты</strong> в меню должника и в карточке студента. Если очень нужно — снять флаг.</li>
    <li><strong>Conditional-доступ не открывается</strong>: <code>ConditionalAccessGranter</code> кидает ошибку «Студент в чёрном списке».</li>
    <li><strong>Разовый доступ к уроку</strong> — кнопка «Выдать доступ к уроку» в карточке студента скрыта, сервис кидает ошибку.</li>
    <li>В строке должника отображается красная иконка 🚩 в подписи студента, при наведении — причина.</li>
</ul>

<h3>Как ставится флаг</h3>
<ul>
    <li><strong>Вручную</strong>: меню действий → «🚩 Отметить как неблагонадёжного». Обязательно указать причину. Сохраняется кто пометил и когда.</li>
    <li><strong>Автоматически</strong>: команда <code>php artisan unreliable:recount</code> (ежедневно в 03:45 после <code>promises:expire</code>) считает количество просроченных (status=expired) обещаний студента за последние 12 месяцев. Если их 3 или больше — выставляется флаг с пометкой «авто» и причиной «Автофлаг: N просроченных обещаний за последние 12 месяцев».</li>
</ul>

<h3>Как снимается флаг</h3>
<p><strong>Только вручную</strong> менеджером — меню действий → «Снять флаг неблагонадёжности». Автоматически он <em>не</em> снимается, даже если поведение улучшилось.</p>
<p>Но при улучшении дисциплины автоматически появляется подсветка: если за 6 месяцев у студента не было ни одной просрочки, выставляется поле <code>discipline_improved_since = today</code>. В тексте подтверждения «снять флаг» менеджеру показывается строка «Поведение улучшилось с MM.YYYY» — подсказка, что можно снять. Если потом опять появляются просрочки, подсветка автоматически сбрасывается.</p>

<div class="warn">
    <strong>Флаг не блокирует существующие доступы.</strong> Если у студента уже открыт conditional-доступ или активная рассрочка, флаг сам по себе их не отменяет. Хотите отозвать конкретное — действуйте через «Отозвать доступ» или «Отменить всю рассрочку».
</div>

<h2>13. Массовые действия</h2>
<p>Слева у каждой строки чекбокс. Отмечаете несколько → внизу появляется меню:</p>
<ul>
    <li><strong>Напомнить в TG/VK</strong> — массовая рассылка. Плейсхолдеры в тексте: <code>{name}</code>, <code>{course}</code>, <code>{block}</code>. Сообщение пойдёт в Telegram и/или VK — куда у студента привязан аккаунт. Студенты без TG и VK попадут в счётчик «без канала».</li>
    <li><strong>Экспорт</strong> — выгрузка выбранных строк в CSV/Excel.</li>
</ul>

<div class="note">
    <strong>Перед массовой рассылкой</strong> отфильтруйте по нужному типу долга и/или конкретному курсу, иначе одинаковая рассылка уйдёт на разные сегменты — это редко даёт хорошую конверсию.
</div>

<h2>14. Карточка студента и RelationManager</h2>
<p>В карточке пользователя (открывается из колонки «Студент» или через «Карточка студента» в меню действий) есть вкладка <strong>«Обещания оплатить»</strong>. Там видно:</p>
<ul>
    <li>Все обещания студента по всем курсам — активные, выполненные, просроченные, отменённые.</li>
    <li><strong>«План»</strong> — короткий id рассрочки (бейдж <span class="badge badge-info">#xxxxxxxx</span>). Если поле пустое — это одиночное обещание.</li>
    <li><strong>«Платёж»</strong> — номер реального платежа, которым закрыто обещание (для выполненных).</li>
    <li><strong>«Доступ»</strong> — <span class="badge badge-success">открыт</span>, если есть активный conditional-доступ.</li>
</ul>
<p>На каждой строке активного промиса доступны действия:</p>
<ul>
    <li><strong>Подтвердить оплату</strong> — создать реальный Payment, закрыть обещание.</li>
    <li><strong>Отменить</strong> — пометить обещание как «Отменено».</li>
    <li><strong>Открыть доступ</strong> — выдать conditional-доступ (если ещё не выдан).</li>
    <li><strong>Отозвать доступ</strong> — забрать conditional-доступ (если выдан).</li>
    <li><strong>Отменить всю рассрочку</strong> — для строк с планом, отменяет все активные обещания плана.</li>
    <li><strong>Редактировать / Удалить</strong> — стандартные действия.</li>
</ul>
<p>Создать новое обещание или рассрочку можно и отсюда — кнопки в правом верхнем углу таблицы. В этом случае нужно дополнительно выбрать курс (на странице «Должники» курс известен из строки).</p>

<h2>15. Автоматика и регламент</h2>
<ul>
    <li><strong>Просроченные обещания</strong> — не закрываются автоматически в момент просрочки, остаются активными, но в списке должников отображаются красным «просрочено DD.MM.YYYY».</li>
    <li><code>php artisan promises:expire</code> — переводит просроченные обещания в статус <span class="badge badge-danger">Просрочено</span>. Запускается ночью в 03:30 по крону.</li>
    <li><code>php artisan unreliable:recount</code> — пересчитывает авто-флаг неблагонадёжности и подсветку «поведение улучшилось». Запускается в 03:45, сразу после <code>promises:expire</code>.</li>
    <li><code>php artisan promises:remind-tomorrow</code> — за день до даты обещания студенту автоматически уходит TG «завтра срок оплаты». Запускается ежедневно в 09:00.</li>
    <li><strong>Conditional-платежи</strong> не отзываются автоматически при просрочке — только менеджер вручную через «Отозвать доступ».</li>
    <li><strong>Платежи через «Подтвердить оплату»</strong> уходят в Google Sheets синхронизацию, как и обычные платежи. Conditional-платежи — НЕ уходят.</li>
</ul>

<h2>16. FAQ</h2>

<h3>Студент оплатил, но колонка «Долг» всё ещё показывает блок</h3>
<p>Проверьте Payment в карточке студента: должны быть заполнены <code>start_block</code> и <code>end_block</code>, статус <code>paid</code> или <code>success</code>, и <code>is_conditional=false</code>. Conditional-платежи (доступ в кредит) намеренно не считаются оплатой долга.</p>

<h3>Сумма долга показывает «≈»</h3>
<p>У курса нет точного тарифа на один из блоков — посчитано по средней цене. Решение — завести точный тариф в админке курса.</p>

<h3>Нужно перенести дату обещания</h3>
<p>«Договориться» (на этом же студенте/курсе) откроется модалкой с уже заполненной датой — меняйте и сохраняйте. В RelationManager — «Редактировать» на строке.</p>

<h3>Студент договорился на рассрочку, но потом захотел оплатить всё разом</h3>
<p>В RelationManager на первой строке плана → «Подтвердить оплату» с полной суммой долга, остальные строки отмените через «Отменить всю рассрочку». Conditional-доступы по этим строкам предварительно отзовите — иначе они «зависнут» без обещания (хотя и не сломают ничего: их можно потом просто удалить).</p>

<h3>Можно ли удалять обещания?</h3>
<p>Технически — да, кнопка «Удалить» в RM есть. Но лучше переводить в «Отменено» — тогда останется история и видно, что договорённость была.</p>

<h3>Куда уходит уведомление о новом платеже?</h3>
<ul>
    <li>Реальная оплата (не conditional, без silent): студенту в Telegram «оплата получена».</li>
    <li>Реальная оплата с silent: ничего студенту, синк в Google Sheets.</li>
    <li>Conditional access (открытие доступа в кредит): студенту «доступ открыт по договорённости до DD.MM», в Google Sheets НЕ уходит.</li>
    <li>Отзыв conditional access: студенту «доступ временно закрыт».</li>
</ul>

<h3>Можно ли дать доступ только на основании обещания, без оплаты?</h3>
<p>Да — раздел 9. Тогл «Открыть доступ» при создании обещания / поля «Откр. с блока №» в строках рассрочки. Это и есть conditional access.</p>

<h3>Студент жалуется: «я был в курсе, теперь не могу зайти»</h3>
<p>Скорее всего у него был conditional-доступ, который отозвали (или не было его никогда — он видел только бесплатные/открытые уроки). Проверьте в карточке студента: на вкладке «Обещания оплатить» посмотрите столбец «Доступ»; в карточке Payments — есть ли paid-платежи с покрывающим тарифом.</p>

