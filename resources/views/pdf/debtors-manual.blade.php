<h2>13a. Скор платежной дисциплины</h2>
<p>Рядом с вкладкой «Обещания оплатить» на карточке студента — блок «Дисциплина»: composite-скор 0–100 и тир (<span class="badge badge-success">Good</span> / <span class="badge badge-warn">Watch</span> / <span class="badge badge-danger">Poor</span>), плюс разбивка по 4 сигналам (оплата вовремя, обещания выполнены, доля доступа «в кредит», случаи молчания). Полная формула, веса и обоснование решений — в <code>docs/discipline-score-spec.md</code>.</p>
<ul>
    <li><strong>Lifetime-метрика</strong> — считается с момента зачисления на каждый курс, отдельно от 12-мес. окна авто-флага 🚩 (<code>unreliable:recount</code>). Обе цифры сосуществуют, одна не заменяет другую.</li>
    <li><strong>Advisory-only</strong> — скор нигде не меняет скидки, не блокирует рассрочку/conditional-доступ и не влияет на порог авто-🚩. Это только контекст для менеджера/преподавателя, решение по-прежнему принимает человек.</li>
    <li><strong>Не персистится</strong> — считается on-demand при каждом открытии карточки/виджета (<code>App\Services\DisciplineScoreService</code>), кешируется только в рамках одного запроса.</li>
    <li><strong>Групповой скор</strong> — на странице «Аналитика студентов» виджет «Дисциплина по группам» показывает простое среднее скора активных участников группы; преподаватель видит только свои группы (read-only).</li>
    <li>Веса и пороги 3-уровневой шкалы — в <code>config/discipline.php</code>, помечены как требующие калибровки после первого прогона на реальных данных.</li>
</ul>

