<h2>1. Зачем нужен сервис</h2>
<p>Сервис показывает студентов, у которых начался блок курса, но он не оплачен. Это рабочий список для звонков, напоминаний и работы с просроченными договорённостями.</p>
<p>Два типичных сценария:</p>
<ul>
    <li><strong>Не продлил</strong> — студент когда-то оплатил предыдущие блоки, а новый — нет. «Тёплый» долг, обычно достаточно напоминания.</li>
    <li><strong>Без оплат</strong> — студент записан на курс, но никогда не платил. Либо лид, либо забытая запись.</li>
</ul>
<div class="note">
    <strong>Кто НЕ попадает в список.</strong> Студенты со статусом обучения <span class="badge badge-danger">Покинул</span>, <span class="badge badge-danger">Исключен</span>, <span class="badge badge-success">Выпускник</span> или <span class="badge badge-warn">Льготник</span> автоматически исключаются — у первых трёх обучение завершено, у льготника оно бесплатное. Статус выставляется в карточке студента → «Обучается на курсах». Для «вышедших» статусов в форме статуса доступно поле <strong>«Блок выхода»</strong>: номер блока этого курса, на/после которого студент вышел/был отчислен/выпустился. Затем показывается в подписи к колонке статуса в этой таблице.
</div>

<h2>2. Как открыть</h2>
<p>В админке Filament: левое меню → «Пользователи» → «Должники». Ссылка <code>/admin/debtors</code>. Доступ только у админов.</p>

<h2>3. Виджет «Общий итог» и «Скоро срок»</h2>
<p>Над таблицей «Должники» — 4 карточки:</p>
<ul>
    <li><strong>Должников (пар user×курс)</strong> — сколько пар в текущей выборке.</li>
    <li><strong>Общий долг</strong> — сумма всех долгов. Если хотя бы у одной пары часть блоков оценена «по средней» (нет точного тарифа) — показывается пометка «(часть «≈»)».</li>
    <li><strong>Просроченных обещаний</strong> — активные promises, дата которых уже прошла. Это первоочередные кандидаты на «отозвать или продлить».</li>
    <li><strong>Неблагонадёжных</strong> — сколько студентов помечены флагом 🚩.</li>
</ul>
<p>На главном дашборде админки добавлен виджет <strong>«Скоро срок оплаты (7 дней)»</strong>. Он показывает обещания, у которых <code>promised_at</code> попадает в ближайшие 7 дней (и просроченные тоже). Это позволяет в начале рабочей недели сразу видеть, у кого подходит срок, без захода в страницу «Должники» и ручной фильтрации.</p>

