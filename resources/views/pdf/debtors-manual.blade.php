<h2>16. FAQ</h2>

<h3>Студент оплатил, но колонка «Долг» всё еще показывает блок</h3>
<p>Проверьте Payment в карточке студента: должны быть заполнены <code>start_block</code> и <code>end_block</code>, статус <code>paid</code> или <code>success</code>, и <code>is_conditional=false</code>. Conditional-платежи (доступ в кредит) намеренно не считаются оплатой долга.</p>

<h3>Сумма долга показывает «≈»</h3>
<p>У курса нет точного тарифа на один из блоков — посчитано по средней цене. Решение — завести точный тариф (<code>type=block</code>, <code>block_number=N</code>) в админке курса.</p>

<h3>Нужно перенести дату обещания</h3>
<p>«Договориться» (на этом же студенте/курсе) откроется модалкой с уже заполненной датой — меняйте и сохраняйте. В карточке студента → «Обещания оплатить» — «Редактировать» на строке.</p>

<h3>Студент договорился на рассрочку, но потом захотел оплатить всё разом</h3>
<p>На первой строке плана → «Подтвердить оплату» с полной суммой долга, остальные строки отмените через «Отменить всю рассрочку». Conditional-доступы по этим строкам сначала отзовите — иначе они «зависнут» без обещания (хотя и не сломают ничего: их можно потом просто удалить).</p>

<h3>Можно ли удалять обещания?</h3>
<p>Технически да, кнопка «Удалить» в RM есть. Но лучше переводить в «Отменено» — тогда останется история и видно, что договоренность была.</p>

<h3>Куда уходит уведомление о платеже?</h3>
<ul>
    <li>Реальная оплата (не conditional, без silent): студенту в Telegram «оплата получена».</li>
    <li>Реальная оплата с silent: ничего студенту, синк в Google Sheets.</li>
    <li>Conditional access (открытие в кредит): студенту «доступ открыт по договоренности до DD.MM», в Google Sheets НЕ уходит.</li>
    <li>Отзыв conditional access: студенту дублированно в TG + email + VK + Max «доступ временно закрыт».</li>
    <li>Разовый доступ к уроку: студенту TG «открыт доступ к уроку …» при выдаче, «доступ к уроку закрыт» при отзыве.</li>
</ul>

<h3>Можно ли дать доступ только под обещание?</h3>
<p>Да — раздел 9. Тогл «Открыть доступ» при создании обещания или поля «Откр. с блока №» в строках рассрочки. Это и есть conditional access.</p>

<h3>Студент пишет «я был в курсе, теперь не могу зайти»</h3>
<p>Скорее всего был conditional-доступ, который отозвали (или его никогда не было — студент видел только бесплатные/открытые уроки). Проверьте в карточке студента: вкладка «Обещания оплатить», столбец «Доступ»; в Payments — есть ли paid-платежи с покрывающим тарифом.</p>

<h3>Студент попал в выборку, хотя уже не учится</h3>
<p>В карточке студента → вкладка «Обучается на курсах» поставьте статус <strong>Покинул</strong> / <strong>Исключен</strong> / <strong>Выпускник</strong> (плюс «Блок выхода»). Со следующего открытия страницы должников он исчезнет — фильтрация делается на уровне SQL.</p>

<h3>Льготник не должен платить — он попал в список</h3>
<p>Поставьте ему по этому курсу статус <strong>Льготник</strong> в «Обучается на курсах». Этот статус полностью исключает пару из выборки должников.</p>

<h3>Не приходит TG-уведомление при отзыве доступа</h3>
<p>После «Отозвать доступ» Filament показывает отчет по каналам: <code>telegram: sent / skipped:no_telegram_id / failed:…</code>. Тот же отчет хранится на обещании в <code>revocation_channels_sent</code>. Если по TG — <em>skipped</em>, значит у студента в карточке не привязан <code>telegram_id</code>; если <em>failed</em> — смотрите детали в логе. Поскольку дублируем сразу во все 4 канала (TG + email + VK + Max), как минимум один обычно доходит.</p>

<h3>Где посмотреть, кто и когда выставил флаг 🚩</h3>
<p>В таблице <code>users</code>: <code>unreliable_marked_at</code> (когда), <code>unreliable_marked_by</code> (кто, FK на users.id), <code>unreliable_auto</code> (true = авто-флаг, false = ручной), <code>unreliable_reason</code> (причина).</p>

