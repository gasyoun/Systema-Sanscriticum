<h2>4. Фильтры и группировка</h2>
<p>Над таблицей справа — кнопка фильтров. Доступно:</p>
<ul>
    <li><strong>Курс</strong> — мультивыбор. Чтобы работать по одному курсу за раз.</li>
    <li><strong>Тип долга</strong> — «не продлившие» / «без оплат». Разные сегменты — разные стратегии общения.</li>
    <li><strong>Каналы связи</strong> — «Есть Telegram», «Есть VK», «Есть Max», «Есть телефон», «Есть email», «Есть Instagram», «Есть Facebook». Чтобы отсечь тех, до кого по этому каналу не достучаться.</li>
    <li><strong>Статус обучения</strong> — мультивыбор активных статусов (Записался / Рассрочка / Приостановка / Вернулся). Полезно, например, сфокусироваться на «Рассрочке» при сверке графиков.</li>
    <li><strong>Неблагонадежные</strong> — «Все» / «Только 🚩» / «Скрыть 🚩».</li>
    <li><strong>Обещание оплатить</strong> — «Все» / «С обещанием» / «Без обещания». Имеет смысл сначала закрыть тех, у кого обещаний еще нет.</li>
</ul>
<p>По умолчанию строки отсортированы по имени студента. Пагинация — 25/50/100 на странице.</p>

<h2>5. Меню действий по строке</h2>
<p>В правом столбце каждой строки — иконка-меню (три точки). Внутри:</p>
<ol>
    <li><span class="badge badge-success">Подтвердить оплату</span> — видно, когда есть активное обещание. Создает реальный Payment и закрывает обещание (раздел 6).</li>
    <li><span class="badge badge-warn">Напомнить в TG/VK</span> — видно, когда у студента привязан хотя бы один мессенджер. Индивидуальное сообщение (раздел 7).</li>
    <li><strong>Договориться</strong> — создать / обновить одиночное обещание. Можно сразу открыть доступ. <em>Скрыто для 🚩.</em></li>
    <li><strong>Рассрочка</strong> — создать план из нескольких обещаний. Можно сразу открывать доступ поблочно. <em>Скрыто для 🚩.</em></li>
    <li><strong>🚩 Отметить как неблагонадежного</strong> — поднять флаг с обязательной причиной (раздел 11).</li>
    <li><strong>Снять флаг неблагонадежности</strong> — видна только когда флаг уже стоит.</li>
    <li><strong>Карточка студента</strong> — открывает полную карточку в новой вкладке.</li>
</ol>

<h2>6. Подтвердить оплату</h2>
<p>Когда деньги пришли, в меню действий → «Подтвердить оплату». В модалке:</p>
<ul>
    <li><strong>Сумма</strong> — подставляется из обещания или из расчетного долга.</li>
    <li><strong>Блок с № / по №</strong> — диапазон неоплаченных блоков по умолчанию.</li>
    <li><strong>Идентификатор транзакции</strong> — по умолчанию <code>promise_#&lt;id&gt;</code>.</li>
    <li>Тогл <strong>«Не уведомлять студента в TG»</strong> (silent) — для фиксации факта прошлой оплаты задним числом, без шумного «оплата получена» прямо сейчас.</li>
</ul>
<p>После «Подтвердить»: создается Payment в статусе <code>paid</code>, обещание становится <span class="badge badge-success">Выполнено</span>, студент попадает в группу курса, начисляется прана, идет синк в Google Sheets.</p>

<div class="warn">
    <strong>silent ≠ conditional access.</strong> silent фиксирует ОПЛАТУ задним числом (фин-отчеты считают ее настоящей), а conditional access (раздел 9) дает ДОСТУП без оплаты (в фин-отчетах не появляется). Не путайте.
</div>

<h2>7. Напоминания в TG / VK</h2>

<h3>Индивидуальное</h3>
<p>В меню действий → «Напомнить в TG/VK». Поля:</p>
<ul>
    <li>Текст с предзаполненным шаблоном. Плейсхолдеры: <code>{name}</code>, <code>{course}</code>, <code>{block}</code>.</li>
    <li>Тогглы «Telegram» и «VK». По умолчанию включены те каналы, что у студента привязаны.</li>
</ul>

<h3>Массовое</h3>
<p>Слева у каждой строки чекбокс. Отметили несколько → внизу появляется кнопка «Напомнить в TG/VK». Те же плейсхолдеры. Студенты без TG и без VK попадут в счетчик «без канала».</p>

<div class="note">
    <strong>Перед массовой рассылкой</strong> отфильтруйте по типу долга и/или курсу. Одно сообщение на разные сегменты редко дает хорошую конверсию.
</div>

<h2>8. Договоренности и рассрочка</h2>

<h3>Одиночное обещание — «Договориться»</h3>
<p>Меню действий → «Договориться». В форме:</p>
<ul>
    <li><strong>Дата обещанной оплаты</strong> — по умолчанию +7 дней.</li>
    <li><strong>Сумма</strong> — можно оставить пустой (= «оплатит весь текущий долг»).</li>
    <li><strong>Комментарий</strong> — например «получит зарплату 25-го».</li>
    <li>Тогл <strong>«Открыть доступ под обещание»</strong> — см. раздел 9.</li>
</ul>
<p>Обещание сохраняется в статусе <span class="badge badge-warn">Активно</span>. Студенту автоматических сообщений не уходит (если не включен тогл «Открыть доступ» — тогда уходит уведомление об открытии).</p>

<h3>Рассрочка</h3>
<p>Меню действий → «Рассрочка». График платежей:</p>
<ul>
    <li>Минимум 2 строки, по умолчанию 3. Первая дата = сегодня + 7, далее с шагом +1 месяц.</li>
    <li>Если сумма долга посчитана — суммы автоподставятся поровну, остаток в последний платеж.</li>
    <li><strong>Факт. дата</strong> — DatePicker для случая, когда деньги по этой строке уже фактически поступили (например, при импорте старого графика задним числом). Пусто = не оплачено. Поле <em>не создает</em> Payment — это просто отметка на обещании.</li>
    <li><strong>Откр. с блока № / по №</strong> — заполняйте, если этот платеж сразу открывает диапазон блоков (см. раздел 9).</li>
    <li>«Комментарий ко всему плану» — общий для всех строк.</li>
</ul>
<p>После сохранения создается N обещаний, объединенных общим id плана. В карточке студента они помечены бейджем <span class="badge badge-info">#xxxxxxxx</span> — короткий id рассрочки.</p>

<div class="warn">
    <strong>Факт. дата без реального Payment долг не закрывает.</strong> Если вы поставили только «Факт. оплата», но не вызвали «Подтвердить оплату», студент остается в списке должников. Это поле для исторической сверки графиков, а не для закрытия задолженности. Если оплата действительно была — проводите ее через «Подтвердить оплату».
</div>

<div class="note">
    <strong>Когда рассрочка, а не одно обещание?</strong> Когда студент явно говорит «по столько-то в месяц», или когда долг большой (3+ блока). Одно обещание — для разовых «оплачу 25-го».
</div>

<h3>Отмена</h3>
<ul>
    <li><strong>Одно обещание</strong> — в карточке студента → вкладка «Обещания оплатить» → «Отменить» на строке. Статус: <span class="badge badge-gray">Отменено</span>.</li>
    <li><strong>Вся рассрочка целиком</strong> — там же на любой строке плана → «Отменить всю рассрочку». Активные обещания плана отменяются разом, выполненные не трогаются.</li>
</ul>

<h2>9. Conditional access — доступ под обещание</h2>
<p>По умолчанию обещание / рассрочка <strong>сами по себе не открывают доступ</strong> — это просто заметка о договоренности. Но если студенту нужно начать учиться до фактической оплаты, можно <strong>открыть доступ в кредит</strong>. Деньги при этом не считаются полученными, должник остается должником в списке, но материалы открываются.</p>

<h3>Два режима</h3>
<ul>
    <li><strong>Весь курс</strong> — открывается весь курс целиком, включая будущие блоки. Хорошо для одиночного обещания.</li>
    <li><strong>Конкретные блоки</strong> — указанные номера. Через запятую (<code>5, 6, 7</code>) или диапазоном (<code>1-3, 5</code>). Хорошо для рассрочки.</li>
</ul>

<h3>При создании одиночного обещания</h3>
<ol>
    <li>«Договориться» → заполните дату, сумму, комментарий.</li>
    <li>Включите тогл «Открыть доступ под обещание».</li>
    <li>Выберите режим (Весь курс / Конкретные блоки), для второго введите номера.</li>
    <li>«Сохранить» → студенту в TG: «Доступ к {курс/блокам} открыт по договоренности до DD.MM».</li>
</ol>

