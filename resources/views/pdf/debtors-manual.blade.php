<h3>Студент может заплатить сам (self-service)</h3>
<p>В личном кабинете студента во вкладке <strong>«Мои долги»</strong> у каждого долга есть кнопка <strong>«Оплатить»</strong>: долг «не продлил» ведет на штатный чекаут по тарифу неоплаченного блока (или всего курса; многоблочный долг можно закрыть одной кнопкой «Оплатить всё»); по рассрочке студент может <strong>внести следующий платеж</strong>, <strong>погасить всё</strong> или <strong>частичную сумму</strong> (от ближайшего взноса до остатка), при желании списав <strong>свою прану</strong> (лояльность/промокод не применяются — сумма зафиксирована). Под «Перенести дату» студент может <strong>один раз</strong> сдвинуть дату ближайшего обещания вперед ≤ 2 недель (вам придет уведомление).</p>
<p>Когда реальная оплата приходит, покрытые ею обещания <strong>закрываются автоматически</strong> (становятся «Выполнено», записывается платеж; частичная оплата закрывает самые ранние взносы), многоблочный платеж открывает <strong>все</strong> оплаченные блоки, и куратор получает уведомление — подтверждать вручную не нужно. Это студенческая половина того же сервиса; ваши инструменты (§6–§9) работают как раньше.</p>

<h2>10. Разовый доступ к одному уроку</h2>
<p>Иногда нужно открыть студенту <strong>один конкретный урок</strong>, без покупки целого блока. Типичный сценарий: первое занятие 1-го блока было бесплатным в рекламных целях, студент пропустил его и хочет вместо этого попасть, например, на 2-е занятие 3-го блока.</p>
<p>Это <strong>общая</strong> возможность — она не привязана ни к долгу, ни к обещанию, и доступна для <em>любого</em> студента, в том числе без активных промисов и без долгов.</p>
<p>Где: карточка студента (<code>/admin/users/{id}/edit</code>) → вкладка <strong>«Разовые доступы к урокам»</strong>. В правом верхнем углу таблицы — кнопка <span class="badge badge-info">Выдать доступ к уроку</span>. В модалке:</p>
<ul>
    <li><strong>Курс</strong> — список всех активных курсов. После выбора курса второй селект становится активным.</li>
    <li><strong>Урок</strong> — все уроки выбранного курса, отсортированы по блокам, подпись «Блок №X · название». Работает поиск по названию.</li>
    <li><strong>Действует до</strong> (опционально) — дата окончания. Пусто = бессрочно.</li>
    <li><strong>Причина</strong> — короткий комментарий для аудита.</li>
</ul>
<p>После «Сохранить» создается запись в <code>lesson_access_grants</code>. Студент сразу видит этот урок открытым, остальной блок остается закрытым. Это не пересекается с conditional access и не влияет на «Долг».</p>
<p><strong>Отзыв</strong>: на строке гранта — кнопка <span class="badge badge-danger">Отозвать</span>. Доступ закрывается, статус — «отозван», студенту в TG уходит «доступ к уроку закрыт». Если у гранта было «действует до» и дата прошла — статус автоматически «истек» (без явного отзыва).</p>
<p>Для студентов с флагом 🚩 кнопка «Выдать доступ к уроку» скрыта (и сервис кидает ошибку — двойная защита).</p>

<h2>11. Неблагонадежные студенты (рецидивисты)</h2>
<p>Если студент <strong>регулярно</strong> срывает обещания оплаты без предупреждения, его «прана сгорает». Это рабочий термин: студент теряет привилегии — скидку лояльности, возможность взять рассрочку и conditional-доступ под честное слово.</p>

<h3>Что меняется при флаге 🚩</h3>
<ul>
    <li><strong>Скидка лояльности отключается.</strong> <code>Tariff::getDiscountPercentForUser()</code> возвращает 0 независимо от количества купленных курсов.</li>
    <li><strong>«Договориться» и «Рассрочка» скрыты</strong> в меню должника и в карточке студента.</li>
    <li><strong>Conditional access не открывается.</strong> Сервис кидает ошибку «Студент в черном списке».</li>
    <li><strong>Разовый доступ к уроку</strong> — кнопка скрыта, сервис тоже отказывает.</li>
    <li>В строке должника — красная иконка 🚩 рядом с именем, при наведении показывается причина.</li>
</ul>

<h3>Как ставится флаг</h3>
<ul>
    <li><strong>Вручную</strong>: меню действий → «🚩 Отметить как неблагонадежного». Причина обязательна. Сохраняется кто пометил и когда.</li>
    <li><strong>Автоматически</strong>: команда <code>php artisan unreliable:recount</code> (ежедневно в 03:45 после <code>promises:expire</code>) считает количество просроченных обещаний студента за последние 12 месяцев. Если 3+ — выставляется флаг с пометкой «авто» и причиной «Автофлаг: N просроченных обещаний за последние 12 месяцев».</li>
</ul>

<h3>Как снимается флаг</h3>
<p><strong>Только вручную</strong> — меню действий → «Снять флаг неблагонадежности». Автоматически не снимается, даже если поведение улучшилось.</p>
<p>Но при улучшении дисциплины автоматически появляется подсветка: если за 6 месяцев у студента не было ни одной просрочки, выставляется поле <code>discipline_improved_since = today</code>. В диалоге «Снять флаг» менеджеру показывается подсказка «Поведение улучшилось с MM.YYYY». Если потом снова появляются просрочки, подсветка сбрасывается.</p>

<div class="warn">
    <strong>Флаг не блокирует существующие доступы.</strong> Если у студента уже открыт conditional-доступ или активная рассрочка, флаг сам по себе их не отменяет. Хотите отозвать конкретное — действуйте через «Отозвать доступ» или «Отменить всю рассрочку».
</div>

