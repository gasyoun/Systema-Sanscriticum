<?php

declare(strict_types=1);

namespace App\Services\Telegram;

use Closure;
use Throwable;

/**
 * Жёсткий потолок времени для одного захода MTProto-синка.
 *
 * Зачем. `telegram-support:sync` ходит в сеть через amphp и умеет зависнуть
 * навсегда (мёртвый IPC-канал, не отвечающий DC). Планировщик защищён только
 * `->withoutOverlapping($ttl)`, а этот замок ПРОТУХАЕТ по TTL — после чего
 * стартует второй экземпляр на той же сессии, хотя первый ещё жив. 27.07.2026
 * на проде так накопилось десять параллельных синков, каждый со своим
 * IPC-демоном; они добили процесс до лимита открытых файлов (EMFILE, 1024).
 * Поэтому заход обязан умирать сам, раньше протухания замка.
 *
 * ## Почему обработчик НЕ бросает исключение (H1915, 30-07-2026)
 *
 * Первая версия (H1904) бросала `MadelineSyncTimedOut` и рассчитывала, что
 * исключение раскрутит стек штатно. На проде 28.07.2026 заход прожил
 * **10 470 с при потолке 120 с** (87x) — и завершился УСПЕШНО (`DONE` в
 * schedule.log, не `FAIL`). Замеры на живом хосте (PHP 8.3.32, pcntl загружен,
 * StreamSelectDriver — ни ev/event/uv в сборке нет) разложили это на две части:
 *
 * 1. **Сигнал доставляется безотказно.** SIGALRM приходит в busy-цикле, внутри
 *    `EventLoop::run()`, при зарегистрированном signal-watcher'е, в `sleep()` и
 *    даже когда процесс блокирован в `flock(LOCK_EX)`. Все четыре гипотезы о
 *    «не взвёлся будильник» — опровергнуты замером.
 * 2. **Исключение из обработчика — нет.** Сигнал прилетает в произвольной точке;
 *    для сетевого синка это почти всегда ВНУТРИ callback'а событийного цикла или
 *    файбера. Revolt отдаёт такое исключение в `EventLoop::setErrorHandler()`, а
 *    MadelineProto ставит туда обработчик, который ЛОГИРУЕТ И ПРОДОЛЖАЕТ
 *    (`AbstractAPI.php:41`, `API.php:429`); сверх того в библиотеке 76 блоков
 *    `catch (Throwable)`, и исключение обязано пережить произвольный из них.
 *    А `pcntl_alarm` ОДНОРАЗОВЫЙ: проглоченный один раз потолок исчезает
 *    насовсем, и остаток захода идёт вообще без ограничения. Ровно это и даёт
 *    связку «10 470 с И код возврата 0».
 *
 * Поэтому обработчик больше не полагается на раскрутку стека: он выполняет
 * переданную уборку (отпустить замок сессии, прибрать демона, пометить аккаунт)
 * и завершает процесс сам — `exit()` из обработчика проверен и работает во всех
 * трёх формах, в которых он может застать заход: в callback'е цикла, на
 * приостановленном главном файбере и внутри тела файбера.
 *
 * Цена решения — `finally` вызывающего НЕ отработает, поэтому вся уборка обязана
 * жить в $onTimeout. Замок `madeline-session` (TTL 900 с) без этого провисел бы
 * четверть часа и заблокировал следующие заходы; см.
 * {@see \App\Console\Concerns\LocksMadelineSession::releaseMadelineSessionLock()}.
 *
 * Без расширения pcntl (в т.ч. на Windows) watchdog — честный no-op: {@see arm()}
 * вернёт false, и вызывающий обязан сказать об этом ГРОМКО: единственной оградой
 * тогда остаётся внешний потолок обёртки (`SYSTEMA_SCHEDULE_MAX_SECONDS`).
 */
class MadelineSyncWatchdog
{
    /**
     * Код выхода процесса, убитого потолком времени. Отличается от обычного
     * FAILURE (1), чтобы «убит watchdog'ом» читалось в логах планировщика и не
     * путалось с рядовой ошибкой синка.
     */
    public const EXIT_TIMED_OUT = 75;

    private bool $armed = false;

    /**
     * Взводит будильник на $seconds. Возвращает false, если таймаут отключён
     * ($seconds <= 0) или pcntl недоступен — тогда заход идёт без потолка.
     *
     * @param  Closure(int):void|null  $onTimeout  уборка ПЕРЕД завершением процесса;
     *                                             получает $seconds. Бросить из неё
     *                                             ничего нельзя — исключение будет
     *                                             проглочено, чтобы неудачная уборка
     *                                             не отменила смерть захода.
     */
    public function arm(int $seconds, ?Closure $onTimeout = null): bool
    {
        if ($seconds <= 0 || ! $this->isSupported()) {
            return false;
        }

        pcntl_async_signals(true);
        pcntl_signal(SIGALRM, function () use ($seconds, $onTimeout): void {
            if ($onTimeout !== null) {
                try {
                    $onTimeout($seconds);
                } catch (Throwable) {
                    // Сознательно глушим: заход обязан умереть, даже если уборка
                    // не удалась. Иначе исключение из уборки уйдёт ровно в тот же
                    // catch (Throwable) библиотеки, из-за которого писан этот класс.
                }
            }

            exit(self::EXIT_TIMED_OUT);
        });
        pcntl_alarm($seconds);

        $this->armed = true;

        return true;
    }

    /**
     * Снимает будильник (заход завершился сам). Идемпотентно.
     */
    public function disarm(): void
    {
        if (! $this->armed) {
            return;
        }

        pcntl_alarm(0);
        $this->armed = false;
    }

    public function isSupported(): bool
    {
        return PHP_OS_FAMILY !== 'Windows'
            && function_exists('pcntl_async_signals')
            && function_exists('pcntl_alarm')
            && function_exists('pcntl_signal');
    }
}
