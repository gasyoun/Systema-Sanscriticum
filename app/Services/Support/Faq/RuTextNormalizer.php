<?php

declare(strict_types=1);

namespace App\Services\Support\Faq;

/**
 * H3766 B3 — лёгкая русская нормализация для BM25 над faq.md.
 *
 * Два независимых слоя:
 *
 * 1. {@see stem()} — усечение словоизменительных окончаний. Применяется
 *    ОДИНАКОВО к корпусу и к запросу, иначе термы перестанут совпадать.
 *    Это не Snowball: нам нужно только свести «оплата/оплатить/оплаты» и
 *    «запись/записи/записей» к одному терму, а не построить лемматизатор.
 *
 * 2. {@see expandQuery()} — расширение ТОЛЬКО запроса синонимами студенческой
 *    речи («зум» → «zoom», «дз» → «домашн», «урок» → «занят»). Расширение, а не
 *    замена: исходный терм остаётся, поэтому синоним не может отнять попадание,
 *    только добавить. В корпус эти пары не подмешиваются.
 *
 * Никаких внешних зависимостей: сервер поддержки работает без vector-стека
 * (запрет эмбеддингов до GPU-ноды — H3234 / #1633).
 */
final class RuTextNormalizer
{
    /** Минимальная длина основы, ниже которой окончание не срезается. */
    private const MIN_STEM = 4;

    /** Проходов по обычным окончаниям («подключение» → «подключ»). */
    private const PASSES = 2;

    /**
     * Возвратные окончания режутся ПЕРВЫМИ и ЗАВЕРШАЮТ разбор.
     *
     * Без этого «записаться» (enrol) двумя проходами схлопывается в «запис» и
     * становится неотличимо от «запись» (recording) — на реальном наборе это
     * стоило −6 п.п. recall@5 по категории B. Со short-circuit «записаться» →
     * «записа» ≠ «запис», как и в Snowball Russian.
     *
     * «ись» в список НЕ входит: «запись» кончается на «ись», и такая ветка
     * съедала бы существительное целиком («зап» короче основы) — терм оставался
     * несклонённым «запись» и переставал совпадать с «записи».
     *
     * @var list<string>
     */
    private const REFLEXIVE = ['ившись', 'вшись', 'ться', 'тся', 'ясь'];

    /**
     * Словоизменительные окончания, длинные раньше коротких.
     *
     * @var list<string>
     */
    private const ENDINGS = [
        'ениями', 'аниями', 'ностью', 'ениях', 'аниях', 'ениям', 'аниям',
        'ением', 'анием', 'остью', 'ования', 'ование',
        'ение', 'ения', 'ению', 'ений', 'ание', 'ания', 'анию', 'аний',
        'ость', 'ости', 'остей', 'ется', 'ются', 'ился', 'илась',
        'ами', 'ями', 'ыми', 'ими', 'ого', 'его', 'ому', 'ему', 'ени', 'ена',
        'ует', 'уют', 'ает', 'ают', 'ить', 'еть', 'ать', 'уть', 'ешь', 'ишь',
        'ах', 'ях', 'ам', 'ям', 'ов', 'ев', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее',
        'ые', 'ие', 'ой', 'ей', 'ью', 'ия', 'ии', 'ем', 'ом', 'ет', 'ут', 'ют',
        'ит', 'ят', 'ла', 'ло', 'ли', 'ть',
        'а', 'е', 'и', 'й', 'о', 'у', 'ы', 'ь', 'я', 'ю',
    ];

    /**
     * Синонимы студенческой речи → термы, которыми это названо в faq.md.
     * Ключ — УЖЕ обрезанная основа; значения тоже основы.
     *
     * @var array<string, list<string>>
     */
    private const SYNONYMS = [
        'зум' => ['zoom'],
        'zoom' => ['зум'],
        'лк' => ['кабинет'],
        'дз' => ['домашн', 'задан'],
        'домашк' => ['домашн', 'задан'],
        'урок' => ['занят'],
        'занят' => ['урок'],
        'видео' => ['запис'],
        'пересмотр' => ['запис', 'пересматрив'],
        'плат' => ['оплат'],
        'платеж' => ['оплат'],
        'оплач' => ['оплат'],
        'деньг' => ['оплат'],
        'логин' => ['парол', 'вход'],
        'войт' => ['вход'],
        'зайт' => ['вход'],
        'попаст' => ['вход'],
        'подключ' => ['вход', 'ссылк'],
        // Возвратные глаголы обрываются на «ться», поэтому мост к корпусной
        // основе задаётся явно: «подключиться» → «подключи» → «подключ».
        'подключи' => ['подключ', 'вход', 'ссылк'],
        'присоедини' => ['присоедин', 'вход'],
        'перевест' => ['перевод', 'смен'],
        'перевед' => ['перевод', 'смен'],
        'чек' => ['квитанц'],
        'диплом' => ['сертификат', 'грамот'],
        'сертификат' => ['грамот'],
        'догнат' => ['пропущ', 'запис'],
        'отста' => ['пропущ', 'запис'],
        'препод' => ['преподавател'],
        'книг' => ['учебник'],
        'учебник' => ['книг'],
        'расписан' => ['занят', 'график'],
        'работа' => [],
    ];

    /** Свернуть ё→е и привести к нижнему регистру. */
    public function fold(string $text): string
    {
        return str_replace(['ё', 'Ё'], 'е', mb_strtolower($text, 'UTF-8'));
    }

    /** Срезать словоизменительные окончания. Идемпотентно по смыслу, не по букве. */
    public function stem(string $token): string
    {
        foreach (self::REFLEXIVE as $ending) {
            if (! str_ends_with($token, $ending)) {
                continue;
            }
            $candidate = mb_substr($token, 0, mb_strlen($token) - mb_strlen($ending));

            return mb_strlen($candidate) >= self::MIN_STEM ? $candidate : $token;
        }

        for ($pass = 0; $pass < self::PASSES; $pass++) {
            $before = $token;
            foreach (self::ENDINGS as $ending) {
                if (! str_ends_with($token, $ending)) {
                    continue;
                }
                $candidate = mb_substr($token, 0, mb_strlen($token) - mb_strlen($ending));
                if (mb_strlen($candidate) >= self::MIN_STEM) {
                    $token = $candidate;
                }
                break;
            }
            if ($token === $before) {
                break;
            }
        }

        return $token;
    }

    /**
     * Дополнить список основ запроса синонимами. Исходные основы сохраняются.
     *
     * @param  list<string>  $stems
     * @return list<string>
     */
    public function expandQuery(array $stems): array
    {
        $out = $stems;
        foreach ($stems as $s) {
            foreach (self::SYNONYMS[$s] ?? [] as $extra) {
                $out[] = $extra;
            }
        }

        return array_values(array_unique($out));
    }
}
