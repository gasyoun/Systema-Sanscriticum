<?php

declare(strict_types=1);

namespace App\Services\Support;

use App\Models\TelegramSupportChat;
use App\Models\TelegramSupportMessage;

/**
 * H6644 — идемпотентность отправителя согласий ПД в TG.
 *
 * Прод-замер 13-10-2026 (агрегатный зонд, секция P1): исходящие
 * LIKE '%соглас%' уходили одному адресату дублями ×2–4 за день
 * (чаты 21/261/262/597/279, все private). Причина — несколько веток
 * автоответчика (шаблон/FAQ/ack/facts/приглашение) каждая со своим
 * cooldown-инвариантом 6 ч: за сутки окно истекает до четырёх раз, и
 * студент получает тот же текст снова.
 *
 * Инварианты (H6644 + доработка 13-11-2026):
 *  1. просьбы о согласии (стем «соглас») — per-chat per-day outgoing ≤ 1;
 *  2. подтверждение «политика принята» — ОДИН РАЗ НАВСЕГДА на чат, а не
 *     «≤1 в день»: согласие уже зафиксировано, просить подтвердить его ещё
 *     раз (сегодня, завтра или через неделю) нечего.
 *
 * Гейт стоит в единственной горловине постановки исходящих
 * ({@see SupportReplyService::createPendingOutgoing}), поэтому покрывает
 * все ботовые ветки разом.
 *
 * Доработка 13-11-2026: прод-лог 18:02 показал две одинаковые копии
 * «✅ Вы приняли политику конфиденциальности / Оператор: ИП Гасунс Марцис».
 * В этом тексте НЕТ стема «соглас», поэтому прежний предикат его не видел
 * и сообщение уходило мимо гейта. Предикат расширен до подтверждений
 * принятия политики, а для них введён отдельный «раз навсегда» счётчик.
 * Просьбы о согласии продолжают считаться исходным стемом «соглас», чтобы
 * метрика зонда P1 совпадала с гейтом байт-в-байт и существующий контракт
 * «один новый запрос согласия на следующий день» не ломался.
 *
 * Намеренно НЕ гейтится:
 *  - человек-куратор (responder_type=human): явная отправка куратором —
 *    осознанное действие, молча гасить её нельзя;
 *  - явное подтверждение человека в полосе подсказок
 *    (SupportHintSendButton → bypass): кнопку «Отправить» нажал человек.
 *
 * Счётчик — по строке БД (sent_at >= начала сегодняшнего дня, Europe/Moscow),
 * включая ещё не доставленные pending: повторная постановка при живом
 * pending — тот же класс дубля.
 */
final class SupportConsentDailyDedup
{
    /** Просьба о согласии (стем зонда P1) либо подтверждение принятия политики. */
    public function isConsentLike(string $text): bool
    {
        return mb_stripos($text, 'соглас') !== false || $this->isPolicyConfirmation($text);
    }

    /**
     * Подтверждение «политика принята» в прошедшем времени.
     *
     * Намеренно НЕ матчит приглашения вида «нажимая кнопку, вы принимаете
     * политику…»: там «принимаете», а не «принял/приняли/принята». Такое
     * приглашение — просьба о согласии, для него остаётся суточный лимит.
     */
    public function isPolicyConfirmation(string $text): bool
    {
        return mb_stripos($text, 'политик') !== false
            && preg_match('/принял|принят/iu', $text) === 1;
    }

    /**
     * Последняя просьба о согласии (стем «соглас») этому чату сегодня,
     * включая ещё не доставленные pending. Подтверждения политики сюда не
     * входят — у них отдельный счётчик «раз навсегда» ниже.
     * Вызывать внутри блокировки строки чата — см. горловину постановки.
     */
    public function findTodaysOutgoing(TelegramSupportChat $chat): ?TelegramSupportMessage
    {
        return TelegramSupportMessage::query()
            ->where('telegram_support_chat_id', $chat->id)
            ->where('direction', 'outgoing')
            ->whereNotNull('text')
            ->where('text', 'like', '%соглас%')
            ->where('sent_at', '>=', now()->startOfDay())
            ->orderByDesc('sent_at')
            ->first();
    }

    /**
     * Уже отправленное этому чату подтверждение принятия политики — за ВСЁ
     * время, без окон и дат. Доставлено или ещё pending — неважно: вторая
     * постановка всё равно была бы дублем в чате студента.
     *
     * SQLite LIKE регистронезависим только для ASCII, поэтому SQL лишь сужает
     * выборку по «олитик» (без первой буквы — ловит и «Политику»), а окончательное
     * решение принимает тот же PHP-предикат isPolicyConfirmation(), что и гейт.
     * Вызывать внутри блокировки строки чата.
     */
    public function findPolicyConfirmation(TelegramSupportChat $chat): ?TelegramSupportMessage
    {
        return TelegramSupportMessage::query()
            ->where('telegram_support_chat_id', $chat->id)
            ->where('direction', 'outgoing')
            ->whereNotNull('text')
            ->where('text', 'like', '%олитик%')
            ->orderBy('id')
            ->get()
            ->first(fn (TelegramSupportMessage $message): bool => $this->isPolicyConfirmation((string) $message->text));
    }
}
