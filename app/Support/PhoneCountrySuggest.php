    /**
     * Страна по телефонному номеру (формат свободный: +41…, 0041…, 8 41… —
     * ведущие +/00/8 срезаются). Null, если код не найден или неоднозначен.
     */
    public static function fromPhone(?string $phone): ?string
    {
        if ($phone === null) {
            return null;
        }

        $digits = preg_replace('/\D+/', '', $phone) ?? '';

        // Международный префикс «00» срезаем; локальный «8» НЕ срезаем —
        // он неоднозначен (8 9… это +7, а 8 41… давало бы ложную Швейцарию).
        if (str_starts_with($digits, '00')) {
            $digits = substr($digits, 2);
        }

        // Самые длинные коды первыми (371 раньше 37, 380 раньше 38…);
        // числовые ключи PHP превращает в int — возвращаем в строки.
        $codes = array_map('strval', array_keys(self::BY_CODE));
        usort($codes, fn (string $a, string $b): int => strlen($b) <=> strlen($a));

        foreach ($codes as $code) {
            if (str_starts_with($digits, $code)) {
                return self::BY_CODE[$code];
            }
        }

        return null;
    }
}
