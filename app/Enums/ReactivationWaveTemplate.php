<?php

declare(strict_types=1);

namespace App\Enums;

use App\Support\MessagePlaceholders;

/**
 * H5288 — два текста волны реактивации A. Построены на ТРЁХ лифтах из
 * win/loss-анализа custdev (см. {@see ReactivationTemplate}): записи занятий,
 * свой темп, рассрочка. Искусственной срочности НЕТ — она даёт −7 к отклику,
 * социальное доказательство −6; поэтому ни «успей», ни «осталось N мест».
 *
 * Тексты живут в коде (а не в MessageTemplate), потому что волна A —
 * разовая кампания с фиксированной копией, которую нужно уметь дословно
 * показать в сухом отчёте до любой отправки. Подстановка — общая
 * {@see MessagePlaceholders}.
 *
 * Ничего не отправляет: это только копия для сухого прогона и для куратора.
 */
enum ReactivationWaveTemplate: string
{
    /** Не продолжил обучение (оплата была недавно) — «вернуться к своей группе». */
    case Continuation = 'wave-a-продолжение';

    /** Уснувший реактивационный пул (оплата давно) — «вернуться с нуля или с того же места». */
    case Return = 'wave-a-возвращение';

    /** Слова-маркеры искусственной срочности — запрещены в текстах волны (лифт −7). */
    public const URGENCY_MARKERS = [
        'успей', 'успейте', 'только сегодня', 'только до', 'последний шанс',
        'осталось мест', 'сгорит', 'сгорает', 'срочно', 'поторопитесь',
    ];

    public function label(): string
    {
        return match ($this) {
            self::Continuation => 'Не продолжил · вернуться к своей группе',
            self::Return => 'Уснувший · тёплое возвращение',
        };
    }

    /** Тема для письма; в Telegram уходит первой строкой. */
    public function subject(): string
    {
        return match ($this) {
            self::Continuation => 'Ваше место на курсе санскрита осталось за вами',
            self::Return => 'Санскрит можно продолжить с того места, где остановились',
        };
    }

    /**
     * Текст шаблона с плейсхолдерами {@see MessagePlaceholders::KEYS}.
     * Три лифта в каждом: записи · свой темп · рассрочка.
     */
    public function body(): string
    {
        return match ($this) {
            self::Continuation => <<<'TXT'
                {name}, здравствуйте.

                Вы занимались у нас санскритом и пока не продолжили — это нормально, у всех бывает занятой период. Хочу напомнить, что возвращаться не обязательно «с начала» и не обязательно в общий ритм:

                1. Все занятия есть в записи — пропущенное можно посмотреть в любое удобное время.
                2. Можно идти в своём темпе: догонять группу постепенно, без дедлайнов.
                3. Оплату можно разбить на части — рассрочка оформляется без процентов, просто напишите в ответ.

                Если сейчас не до учёбы — ничего страшного, просто ответьте «позже», и я не буду писать по этому поводу. Если хочется вернуться — ответьте, и мы подберём, с какого места вам удобнее продолжить: {pay_link}

                С уважением,
                команда «Мир санскрита»
                TXT,
            self::Return => <<<'TXT'
                {name}, здравствуйте.

                Мы давно не виделись на занятиях по санскриту, и я пишу без всякого повода продать — скорее сказать, что дверь открыта. За это время курс стал удобнее для тех, кто возвращается:

                1. Занятия доступны в записи — можно начать смотреть, не подстраиваясь под расписание.
                2. Темп ваш: хоть одно занятие в неделю, хоть три за вечер, группа никого не подгоняет.
                3. Если вопрос в деньгах — есть рассрочка; она оформляется по одному сообщению.

                Возвращаться можно и с нуля, и с того места, где остановились — мы посмотрим вместе, что вы помните, и выберем точку входа: {pay_link}

                Если писать больше не нужно — ответьте одним словом «не писать», и я уберу вас из рассылки.

                С уважением,
                команда «Мир санскрита»
                TXT,
        };
    }

    /** Какой половине когорты предлагается этот текст. */
    public static function forSegment(string $segment): self
    {
        return $segment === 'non_continuer' ? self::Continuation : self::Return;
    }

    /**
     * Найденные маркеры срочности в тексте (пусто = чисто). Пин для теста:
     * копия волны не должна давить.
     *
     * @return list<string>
     */
    public static function urgencyHits(string $text): array
    {
        $haystack = mb_strtolower($text);

        return array_values(array_filter(
            self::URGENCY_MARKERS,
            static fn (string $marker): bool => str_contains($haystack, $marker),
        ));
    }
}
