    private static function stage(int $n, string $title, string $subtitle, string $c1, string $c2): string
    {
        $dots = '';
        for ($i = 1; $i <= 5; $i++) {
            $bg = $i <= $n ? 'rgba(255,255,255,.95)' : 'rgba(255,255,255,.28)';
            $dots .= '<span style="width:11px;height:11px;border-radius:9999px;background:'.$bg.';display:inline-block"></span>';
        }

        return <<<HTML
        <div style="border-radius:24px;padding:30px 26px;margin-bottom:22px;background:linear-gradient(135deg,$c1,$c2);color:#fff;font-family:inherit">
          <div style="font-size:11px;font-weight:800;letter-spacing:.18em;text-transform:uppercase;opacity:.85">Этап {$n} из 5</div>
          <div style="display:flex;gap:6px;margin-top:10px">$dots</div>
