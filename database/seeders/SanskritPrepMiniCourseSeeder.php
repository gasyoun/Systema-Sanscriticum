    private function seedBlocksLessonsAndQuizzes(): void
    {
        $course = Course::where('slug', self::SLUG)->firstOrFail();

        foreach ($this->stages() as $stage) {
            CourseBlock::updateOrCreate(
                ['course_id' => $course->id, 'number' => $stage['number']],
                [
                    'title' => $stage['block_title'],
                    'description' => $stage['block_description'],
                    'is_active' => true,
                ],
            );

            foreach ($stage['lessons'] as $lessonData) {
                Lesson::updateOrCreate(
                    ['course_id' => $course->id, 'title' => $lessonData['title']],
                    [
                        'topic' => $lessonData['topic'] ?? null,
                        'content_html' => $lessonData['content_html'] ?? null,
                        'lesson_date' => $lessonData['lesson_date'],
                        'block_number' => $stage['number'],
                        'youtube_url' => $lessonData['youtube_url'] ?? null,
                        'video_url' => $lessonData['video_url'] ?? null,
                        'is_published' => true,
                        'is_free' => true,
                        'show_on_main' => false,
                        'recording_kind' => 'course_lesson',
                        'homework_enabled' => $lessonData['homework'] ?? false,
                        'homework_prompt' => $lessonData['homework_prompt'] ?? null,
                    ],
                );
            }

            $quiz = CourseQuiz::updateOrCreate(
                ['course_id' => $course->id, 'block_number' => $stage['number']],
                [
                    'title' => $stage['quiz']['title'],
                    'description' => $stage['quiz']['description'],
                    'pass_score' => 60,
                    'is_active' => true,
                ],
            );

            // Попытки ссылаются на квиз, не на вопрос — пересоздание безопасно.
            $quiz->questions()->delete();
            foreach ($stage['quiz']['questions'] as $sort => $q) {
                CourseQuizQuestion::create([
                    'course_quiz_id' => $quiz->id,
                    'question' => $q[0],
                    'options' => $q[1],
                    'correct_option' => $q[2],
                    'explanation' => $q[3] ?? null,
                    'sort_order' => $sort,
                ]);
            }
        }

        $this->seedFinalQuiz($course);
    }

    /**
     * Итоговый тест курса (перенос Google-формы бота) — квиз с block_number 6:
     * вне этапов, охватывает все пять. Показывается на странице курса
     * с бейджем «Финал».
     */
    private function seedFinalQuiz(Course $course): void
    {
        $quiz = CourseQuiz::updateOrCreate(
            ['course_id' => $course->id, 'block_number' => 6],
