#!/usr/bin/env python3
"""H6917 — FAQ corpus citation-key drift gate.

`resources/knowledge/faq.md` is generated by ORS-FAQ (`python -m
ors_faq.tools.export_bot_kb`) and is re-exported every time the wiki changes.
Every `###` heading is a corpus section, and its chunk_id is the heading-path
slug (FaqCorpusParser::chunkIdFromPath, app/Services/Support/Faq/FaqCorpusParser.php).
Because the eval fixture (`tests/fixtures/faq_rag_eval.json`) cites those
chunk_ids, a re-export that renames a heading silently invalidates the citation
keys: on 17-10-2026 the sync renamed all 81 `###` headings and 26 of the 29
distinct expected ids went dead while `FaqRagEvalTest` was still asserting
their presence.

This gate compares the exported corpus' chunk-id SET with the citation keys the
eval fixture expects, and (optionally) with a fresh export from ORS-FAQ HEAD.
It fails on KEY drift, not byte drift: rewording a body is fine, renaming a
heading is not, because the fixture and every stored `faq_chunk_id` point at the
old key.

Usage:
    python scripts/check_faq_corpus_drift.py --check
    python scripts/check_faq_corpus_drift.py --check --json
    # compare against a fresh ORS-FAQ export before syncing it in:
    python -m ors_faq.tools.export_bot_kb -o /tmp/faq_head.md   # in ORS-FAQ
    python scripts/check_faq_corpus_drift.py --check --upstream /tmp/faq_head.md

Exit codes:
    0  corpus, fixture and (when given) upstream agree on every citation key
    1  drift — a key moved, a key is duplicated, or the fixture cites a key the
       corpus cannot produce (the failing keys are printed by name)
    2  usage / unreadable input (corpus or fixture missing, empty parse)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CORPUS = REPO_ROOT / "resources" / "knowledge" / "faq.md"
DEFAULT_FIXTURE = REPO_ROOT / "tests" / "fixtures" / "faq_rag_eval.json"

H1_RE = re.compile(r"^#\s+")
H2_RE = re.compile(r"^##\s+(.+)$")
H3_RE = re.compile(r"^###\s+(.+)$")


def slug_part(part: str) -> str:
    """Port of FaqCorpusParser::chunkIdFromPath() for one heading-path part.

    PHP: mb_strtolower(trim($part)) -> replace /[^\\p{L}\\p{N}]+/u with '-'
    -> trim('-') -> 'section-' . substr(md5($part), 0, 8) when empty.
    """
    slug = part.strip().lower()
    # \\W is "not a word character"; the underscore is a word character in both
    # PHP's \\p{L}\\p{N} sense and Python's \\w, so it must be excluded by hand.
    slug = re.sub(r"[\W_]+", "-", slug)
    slug = slug.strip("-")
    if slug == "":
        # PHP hashes the ORIGINAL (unstripped, original-case) part.
        slug = "section-" + hashlib.md5(part.encode("utf-8")).hexdigest()[:8]
    return slug


def chunk_id_for(path: list[str]) -> str:
    return "/".join(slug_part(part) for part in path)


def parse_sections(text: str) -> list[dict]:
    """Port of FaqCorpusParser::parseFile() — (chunk_id, title, body) triples.

    Rules, in the parser's order: `###` opens an H3 (flushing the pending
    section), `##` opens an H2 and clears the H3, `#` is a document title and
    neither opens nor closes a section, lines beginning with `<!--` are skipped.
    A section is emitted when it has a heading path and either a non-empty body
    or an H3 (an empty `###` still counts, exactly like the PHP side).
    """
    sections: list[dict] = []
    h2: str | None = None
    h3: str | None = None
    body: list[str] = []

    def flush() -> None:
        nonlocal h2, h3, body
        if h2 is None and h3 is None:
            body = []
            return
        text_body = "\n".join(body).strip()
        if text_body == "" and h3 is None:
            body = []
            return
        path = [part for part in (h2, h3) if part]
        if not path:
            body = []
            return
        sections.append(
            {
                "id": chunk_id_for(path),
                "heading_path": path,
                "title": h3 or h2 or "",
                "body": text_body,
            }
        )
        body = []

    for line in re.split(r"\r\n|\n|\r", text):
        match = H3_RE.match(line)
        if match:
            flush()
            h3 = match.group(1).strip()
            body = []
            continue
        match = H2_RE.match(line)
        if match:
            flush()
            h2 = match.group(1).strip()
            h3 = None
            body = []
            continue
        if H1_RE.match(line):
            continue
        if line.strip().startswith("<!--"):
            continue
        body.append(line)
    flush()
    return sections


def load_corpus(path: Path) -> list[dict]:
    return parse_sections(path.read_text(encoding="utf-8"))


def duplicated_ids(sections: list[dict]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for section in sections:
        counts[section["id"]] = counts.get(section["id"], 0) + 1
    return {key: count for key, count in counts.items() if count > 1}


def fixture_expectations(path: Path) -> dict[str, list[str]]:
    """expected chunk_id -> the eval item ids that cite it (sorted)."""
    data = json.loads(path.read_text(encoding="utf-8"))
    items = data.get("items") or []
    expected: dict[str, list[str]] = {}
    for item in items:
        for key in item.get("expected_chunk_ids") or []:
            expected.setdefault(str(key), []).append(str(item.get("id", "?")))
    return expected


def report(
    *,
    corpus_path: Path,
    fixture_path: Path,
    sections: list[dict],
    expected: dict[str, list[str]],
    upstream: Path | None = None,
    as_json: bool = False,
) -> int:
    corpus_ids = [section["id"] for section in sections]
    corpus_id_set = set(corpus_ids)
    duplicates = duplicated_ids(sections)
    missing = sorted(key for key in expected if key not in corpus_id_set)

    upstream_only: list[str] = []
    corpus_only: list[str] = []
    upstream_note = ""
    if upstream is not None:
        upstream_ids = {section["id"] for section in load_corpus(upstream)}
        if not upstream_ids:
            print(f"ERROR: upstream {upstream} parsed to zero chunks", file=sys.stderr)
            return 2
        upstream_only = sorted(upstream_ids - corpus_id_set)
        corpus_only = sorted(corpus_id_set - upstream_ids)
        upstream_note = f", upstream {len(upstream_ids)}"

    ok = not missing and not duplicates and not upstream_only and not corpus_only

    if as_json:
        print(
            json.dumps(
                {
                    "ok": ok,
                    "corpus": str(corpus_path),
                    "corpus_chunks": len(sections),
                    "fixture": str(fixture_path),
                    "expected_keys": len(expected),
                    "missing_keys": missing,
                    "duplicate_keys": duplicates,
                    "upstream": str(upstream) if upstream else None,
                    "keys_only_upstream": upstream_only,
                    "keys_only_local": corpus_only,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
        return 0 if ok else 1

    print(
        f"corpus: {corpus_path} — {len(sections)} chunks; "
        f"fixture: {fixture_path} — {len(expected)} distinct citation keys"
        f"{upstream_note}"
    )

    if duplicates:
        print("\nDRIFT: duplicate chunk_id — the second body silently overwrites "
              "the first in knowledge_chunks (faq_chunk_id is unique):")
        for key, count in sorted(duplicates.items()):
            print(f"  {key}  ×{count}")

    if missing:
        print("\nDRIFT: citation key(s) the corpus cannot produce "
              "(a heading was renamed, moved or removed):")
        for key in missing:
            items = ", ".join(sorted(expected[key])[:8])
            more = "" if len(expected[key]) <= 8 else f", +{len(expected[key]) - 8} more"
            print(f"  {key}  — cited by {items}{more}")

    if upstream_only:
        print(f"\nDRIFT: {len(upstream_only)} key(s) exist upstream but not in the "
              "local export (the corpus is stale — run the ORS-FAQ export):")
        for key in upstream_only[:20]:
            print(f"  {key}")
        if len(upstream_only) > 20:
            print(f"  … +{len(upstream_only) - 20} more")

    if corpus_only:
        print(f"\nDRIFT: {len(corpus_only)} key(s) exist locally but not upstream "
              "(renamed/removed upstream — every stored faq_chunk_id for them is dead):")
        for key in corpus_only[:20]:
            print(f"  {key}")
        if len(corpus_only) > 20:
            print(f"  … +{len(corpus_only) - 20} more")

    if ok:
        print("\nOK: every citation key resolves; no duplicate chunk_id.")
        return 0

    print("\nFAIL: fix the corpus/fixture (see keys above) — this is citation-key "
          "drift, not byte drift.")
    return 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="H6917: FAQ corpus citation-key drift gate "
                    "(corpus chunk-ids vs eval-fixture keys vs ORS-FAQ export)."
    )
    parser.add_argument("--check", action="store_true",
                        help="run the gate (required; the flag exists so CI and "
                             "humans share one invocation shape)")
    parser.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS,
                        help=f"corpus markdown (default: {DEFAULT_CORPUS})")
    parser.add_argument("--fixture", type=Path, default=DEFAULT_FIXTURE,
                        help=f"eval fixture json (default: {DEFAULT_FIXTURE})")
    parser.add_argument("--upstream", type=Path, default=None,
                        help="optional fresh faq.md exported from ORS-FAQ HEAD — "
                             "enables the set comparison against upstream")
    parser.add_argument("--json", action="store_true", dest="as_json",
                        help="machine-readable verdict on stdout")
    args = parser.parse_args(argv)

    if not args.check:
        parser.print_help(sys.stderr)
        return 2

    for path, label in ((args.corpus, "corpus"), (args.fixture, "fixture")):
        if not path.is_file():
            print(f"ERROR: {label} not found: {path}", file=sys.stderr)
            return 2

    sections = load_corpus(args.corpus)
    if not sections:
        print(f"ERROR: {args.corpus} parsed to zero chunks", file=sys.stderr)
        return 2

    expected = fixture_expectations(args.fixture)
    if not expected:
        print(f"ERROR: {args.fixture} carries no expected_chunk_ids", file=sys.stderr)
        return 2

    return report(
        corpus_path=args.corpus,
        fixture_path=args.fixture,
        sections=sections,
        expected=expected,
        upstream=args.upstream,
        as_json=args.as_json,
    )


if __name__ == "__main__":
    sys.exit(main())
